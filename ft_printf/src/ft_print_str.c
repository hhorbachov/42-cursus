#include "../ft_printf.h"

int	ft_printf_str(char *s)
{
	int	len;

	if (!s)
		return (0);
	len = ft_strlen(s);
	while (*s)
	{
		ft_print_char(*s);
		s++;
	}
	return (len);
}
